function stem(word: string): string {
  const normalized = word.toLowerCase().replaceAll("ё", "е");
  if (normalized.length <= 4) return normalized;
  return normalized.slice(0, 5);
}

function tokens(text: string): string[] {
  return text
    .toLowerCase()
    .replaceAll("ё", "е")
    .split(/[^a-zа-я0-9]+/i)
    .map((word) => word.trim())
    .filter((word) => word.length >= 3)
    .map(stem);
}

export function rankKnowledgeSections(
  question: string,
  sections: KnowledgeSection[] = MANAGER_KNOWLEDGE,
  limit = 3
): KnowledgeSection[] {
  const query = [...new Set(tokens(question))];
  if (query.length === 0) return [];

  const ranked = sections
    .map((section) => {
      const titleStems = new Set(tokens(section.title));
      const keywordStems = new Set(section.keywords.map(stem));
      const bodyStems = new Set(tokens(section.text));
      let score = 0;
      for (const word of query) {
        if (keywordStems.has(word)) score += 4;
        else if (titleStems.has(word)) score += 3;
        else if (bodyStems.has(word)) score += 1;
      }
      return { section, score };
    })
    .filter((item) => item.score > 0)
    .sort((left, right) => right.score - left.score);

  return ranked.slice(0, limit).map((item) => item.section);
}
