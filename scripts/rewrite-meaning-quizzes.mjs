function applyBanks(filePath, itemsKey, banks, extra) {
  const catalog = JSON.parse(fs.readFileSync(filePath, "utf8"));
  for (const item of catalog[itemsKey]) {
    const bank = banks[item.id];
    if (!bank) {
      console.warn(`No quiz bank for ${item.id}`);
      continue;
    }
    item.questions = bank;
    extra?.(item);
    console.log(`${item.id}: ${item.questions.length} questions`);
  }
  fs.writeFileSync(filePath, `${JSON.stringify(catalog, null, 2)}\n`, "utf8");
}

